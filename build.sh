#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")"
BUILD_DIR="${BUILD_DIR:-$(mktemp -d /private/tmp/codexquota.XXXXXX)}"
SIGN_IDENTITY="${SIGN_IDENTITY:--}"
APP_GROUP="${APP_GROUP:-group.local.codexquota}"
mkdir -p "$BUILD_DIR/Codex 周额度.app/Contents/MacOS" "$BUILD_DIR/Codex 周额度.app/Contents/PlugIns/CodexQuotaWidget.appex/Contents/MacOS" "$BUILD_DIR/module-cache"
APP="$BUILD_DIR/Codex 周额度.app"
EXT="$APP/Contents/PlugIns/CodexQuotaWidget.appex"
export CLANG_MODULE_CACHE_PATH="$BUILD_DIR/module-cache"
mkdir -p "$APP/Contents/Resources" "$EXT/Contents/Resources"
cp Assets/AppIcon-rounded.icns "$APP/Contents/Resources/QuotaAppIcon-v6.icns"
cp Assets/AppIcon-rounded.icns "$EXT/Contents/Resources/QuotaAppIcon-v6.icns"
python3 scripts/metadata.py "$APP" "$EXT" "$APP_GROUP" "$BUILD_DIR"
xcrun swiftc -swift-version 5 -parse-as-library -O -target arm64-apple-macos26.0 Sources/Quota.swift Sources/CodexClient.swift Sources/LocalQuotaServer.swift Sources/QuotaView.swift Sources/QuotaApp.swift -o "$APP/Contents/MacOS/CodexQuota"
xcrun swiftc -swift-version 5 -parse-as-library -application-extension -Xlinker -e -Xlinker _NSExtensionMain -O -target arm64-apple-macos26.0 Sources/Quota.swift Sources/QuotaView.swift Sources/QuotaWidget.swift -o "$EXT/Contents/MacOS/CodexQuotaWidget"
codesign --force --sign "$SIGN_IDENTITY" --entitlements "$BUILD_DIR/widget.entitlements" "$EXT"
codesign --force --sign "$SIGN_IDENTITY" --entitlements "$BUILD_DIR/app.entitlements" "$APP"
codesign --verify --deep --strict "$APP"
printf 'Built: %s\n' "$APP"
